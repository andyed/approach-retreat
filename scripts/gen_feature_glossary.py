def emit_markdown_table() -> str:
    lines = [
        "| Feature | Type / units | Definition | Formula sketch | Model sets |",
        "|---|---|---|---|---|",
    ]
    for group, names in GROUPS:
        lines.append(f"| **{group}** | | | | |")
        for n in names:
            g = GLOSSARY[n]
            lines.append(
                f"| `{n}` | {g['units']} | {g['defn']} | {g['formula']} | {g['models']} |"
            )
    return "\n".join(lines)


def emit_markdown_doc() -> str:
    return (
        f"{MARKER_START}\n\n"
        "# Feature glossary\n\n"
        f"> {PROVENANCE}\n\n"
        f"{INTRO_MD}\n\n"
        f"{emit_markdown_table()}\n\n"
        f"{MARKER_END}\n"
    )


TEX_SPECIALS = {
    "_": r"\_",
    "#": r"\#",
    "%": r"\%",
    "&": r"\&",
    "−": "$-$",
    "≥": "$\\geq$",
    "≠": "$\\neq$",
    "↔": "$\\leftrightarrow$",
    "→": "$\\to$",
    "∧": "$\\wedge$",
    "Δ": "$\\Delta$",
    "—": "---",
    "§": "\\S",
    "–": "--",
}


def tex_escape(s: str) -> str:
    out = []
    for ch in s:
        out.append(TEX_SPECIALS.get(ch, ch))
    return "".join(out)


def emit_tex() -> str:
    header = r"""% ---------------------------------------------------------------------------
% feature_glossary.tex — GENERATED FILE, DO NOT HAND-EDIT.
% Source of truth: approach-retreat/scripts/gen_feature_glossary.py, which
% parses ResultFeatureTracker in approach-retreat/src/approach-retreat.js,
% cross-checks M4_FEATURES in attentional-foraging/scripts/
% m4_nb21_hybrid_rerun.py (JS<->Python parity 1e-6), and the WILD analog
% extractor in approach-retreat/analysis/attcur-validation/run_analysis.py.
% Regenerate:  python3 ~/Documents/dev/approach-retreat/scripts/gen_feature_glossary.py
%
% WHERE TO \input THIS: at the end of §3.4 ("Leaky Cursor Approach
% Features", label the-seven-approach-features-m4-cursor-probe) in
% 3_method_new.tex, immediately after the fig:leakycursor figure block —
% i.e. add the line
%     \input{feature_glossary}
% there. Addresses Reviewer 2 (feature names used but never defined,
% e.g. total_dwell_ms vs dwell_in_target_ms) and Reviewer 3 (§3.4 does
% not teach the seven features). Uses only booktabs + adjustbox, both
% already loaded by 0_paper.tex. Reference it as Table~\ref{tab:glossary}.
% ---------------------------------------------------------------------------
"""
    rows = []
    for group, names in GROUPS:
        rows.append(r"\midrule")
        rows.append(
            r"\multicolumn{4}{@{}l}{\textit{" + tex_escape(group) + r"}} \\"
        )
        rows.append(r"\midrule")
        for n in names:
            g = GLOSSARY[n]
            defn = tex_escape(g["defn"])
            cell = f"{defn} \\emph{{Formula:}} {g['formula_tex']}."
            rows.append(
                f"\\texttt{{{tex_escape(n)}}} & {tex_escape(g['units'])} & "
                f"{cell} & {tex_escape(g['models'])} \\\\"
            )
            rows.append(r"\addlinespace[2pt]")
    body = "\n".join(rows)
    return (
        header
        + r"""
\begin{table*}[t]
\footnotesize
\centering
\caption{\textbf{Feature glossary.} Every behavioral feature named in
this paper, generated from the reference implementations
(\texttt{approach-retreat} JS library and the parity-verified Python
extractor; WILD analogs from the ACD validation harness). All LAB
features are transformations of the cursor-to-AOI distance
$d(t) = |y_{\mathrm{cursor}}(t) - y_{\mathrm{AOI}}|$ (page-space
vertical distance), aggregated over the whole click-buffered trial;
directed velocity $v(t) = -\Delta d / \Delta t$ is positive when
approaching. M4 is the seven buffer-robust features: the nine computed
minus \texttt{final\_dist} and \texttt{retreat\_dist} (\S5.2 leakage
screen). The WILD (ACD) analog vector re-derives the construction for
cursor+click-only telemetry.}
\label{tab:glossary}
\adjustbox{max width=\textwidth}{%
\begin{tabular}{@{}llp{9.2cm}p{4.2cm}@{}}
\toprule
Feature & Units & Definition & Model sets \\
"""
        + body
        + "\n"
        + r"""\bottomrule
\end{tabular}%
}
\end{table*}
"""
    )


def update_readme(table_block: str) -> bool:
    text = README.read_text()
    if MARKER_START not in text or MARKER_END not in text:
        return False
    pattern = re.compile(
        re.escape(MARKER_START) + r".*?" + re.escape(MARKER_END), re.S
    )
    new = pattern.sub(table_block.rstrip("\n"), text)
    README.write_text(new)
    return True


def main():
    run_guards()

    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(emit_markdown_doc())
    print(f"wrote {OUT_MD}")

    OUT_TEX.write_text(emit_tex())
    print(f"wrote {OUT_TEX}")

    readme_block = (
        f"{MARKER_START}\n\n"
        f"### Feature glossary\n\n"
        f"> {PROVENANCE}\n"
        f"> Full version with intro notes: "
        f"[`docs/feature-glossary.md`](docs/feature-glossary.md).\n\n"
        f"{emit_markdown_table()}\n\n"
        f"{MARKER_END}"
    )
    if update_readme(readme_block):
        print(f"updated {README} (between glossary markers)")
    else:
        print(
            f"README markers not found — skipped README update.\n"
            f"  Add these markers to README.md to enable:\n"
            f"  {MARKER_START}\n  {MARKER_END}"
        )


if __name__ == "__main__":
    main()
