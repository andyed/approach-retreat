def fail(msg: str) -> None:
    print(f"DRIFT GUARD FAILED: {msg}", file=sys.stderr)
    sys.exit(1)


# ─────────────────────────────────────────────────────────────────────
# Parsers
# ─────────────────────────────────────────────────────────────────────

def parse_js(js_text: str):
    """Return (comment_names, getfeatures_keys, has_total_dwell)."""
    # 1. The structured comment block above ResultFeatureTracker:
    #    " *   1. min_dist              — min |Δy| ..."
    comment_names = re.findall(
        r"^\s*\*\s*\d+\.\s+(\w+)\s+—", js_text, re.M
    )
    if not comment_names:
        fail("could not parse the numbered feature comment block in approach-retreat.js")

    # 2. getFeatures() return keys.
    m = re.search(r"getFeatures\(\)\s*\{(.*?)\n  \}", js_text, re.S)
    if not m:
        fail("could not locate getFeatures() body in approach-retreat.js")
    body = m.group(1)
    keys = re.findall(r"^\s+(\w+):", body, re.M)
    if not keys:
        fail("getFeatures() body parsed but no return keys found")

    has_total_dwell = "total_dwell_ms" in js_text
    return comment_names, keys, has_total_dwell


def parse_py_m4(py_text: str):
    m = re.search(r"M4_FEATURES\s*=\s*\[(.*?)\]", py_text, re.S)
    if not m:
        fail("could not locate M4_FEATURES in m4_nb21_hybrid_rerun.py")
    return re.findall(r'"(\w+)"', m.group(1))


def parse_wild(py_text: str):
    m = re.search(r"def compute_features.*?return \{(.*?)\n    \}", py_text, re.S)
    if not m:
        fail("could not locate compute_features() return dict in run_analysis.py")
    return re.findall(r'"(\w+)":', m.group(1))


# ─────────────────────────────────────────────────────────────────────
# Drift guards
# ─────────────────────────────────────────────────────────────────────

def run_guards():
    js_text = JS_SRC.read_text()
    comment_names, gf_keys, has_total_dwell = parse_js(js_text)
    py_m4 = parse_py_m4(PY_EXTRACTOR.read_text())
    wild_keys = parse_wild(WILD_SRC.read_text())

    # Guard 1: comment block == getFeatures keys minus sample_count, same order.
    gf_features = [k for k in gf_keys if k != "sample_count"]
    if comment_names != gf_features:
        fail(
            "JS comment block and getFeatures() disagree:\n"
            f"  comment:      {comment_names}\n"
            f"  getFeatures:  {gf_features}"
        )

    # Guard 2: Python M4_FEATURES == the nine JS features, same order.
    if py_m4 != comment_names:
        fail(
            "Python M4_FEATURES and JS tracker disagree:\n"
            f"  M4_FEATURES:  {py_m4}\n"
            f"  JS:           {comment_names}"
        )

    # Guard 3: total_dwell_ms still exists in the JS (getSignals aggregate).
    if not has_total_dwell:
        fail("total_dwell_ms no longer present in approach-retreat.js")

    # Guard 4: every WILD name in the glossary exists in run_analysis.py.
    wild_glossary = GROUPS[2][1]
    missing = [n for n in wild_glossary if n not in wild_keys]
    if missing:
        fail(f"WILD glossary names missing from run_analysis.py: {missing}")

    # Guard 5: curated glossary keys exactly cover the code-derived set.
    code_names = set(gf_keys) | {"total_dwell_ms"} | set(wild_glossary)
    glossary_names = set(GLOSSARY)
    group_names = [n for _, names in GROUPS for n in names]
    if sorted(group_names) != sorted(glossary_names):
        fail(
            "GROUPS and GLOSSARY disagree: "
            f"{set(group_names) ^ glossary_names}"
        )
    only_code = code_names - glossary_names
    only_glossary = glossary_names - code_names
    if only_code:
        fail(
            f"feature(s) computed in code but missing a glossary row: {sorted(only_code)}"
        )
    if only_glossary:
        fail(
            f"glossary row(s) with no code referent: {sorted(only_glossary)}"
        )

    return comment_names


